TX = ['brief', 'opening', 'process', 'ending', 'conclusion']
def fx(oid, rk, note, pairs, extra_conf=None):
    o = old_spec(oid)
    over = {}
    for a, b in pairs:
        hit = [k for k in TX if a in (over.get(k) or o[k])]
        assert len(hit) == 1, (oid, a, hit)
        k = hit[0]
        over[k] = (over.get(k) or o[k]).replace(a, b)
    conf = (o.get('conflicts') or []) + ([extra_conf] if extra_conf else [])
    v2(oid, rk, note, conflicts=conf, **over)
